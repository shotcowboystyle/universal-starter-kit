// Vite config factory for the VS Code target of a One platform app.
//
// The target lives INSIDE the product app (apps/<name>/vscode/) — the same
// pattern as the GNOME/webext targets — with the layout
// @tomjs/vite-plugin-vscode's `recommended` mode expects:
//
//   apps/<name>/vscode/
//     index.html            ← webview entry (vite root)
//     extension/index.ts    ← extension host (built by tsdown via the plugin)
//     webview/…             ← webview React sources
//
// Outputs land under `outDir` as extension/ + webview/;
// `writeVsceManifest` then drops the extension-manifest package.json next
// to them so `vsce package` can run against the staging dir — the product
// app's own package.json is an Expo/One manifest and can't double as the
// extension's.
//
// One routing layer: the factory aliases `one` to the stack-navigation
// seam's one-adapter (@repo/router/seam), so feature screens,
// @package/layouts and the router facade all ride the seam — a webview has
// no address bar and no One server runtime for One's real router.

import fs from 'node:fs';
import path from 'node:path';

import {
  lookupTamaguiModules,
  lookupProjectRoot,
  oneServerOnlyBrowserStub,
  stubExpoTypeDeclarations,
  workspaceSourceAliases,
} from '@repo/utils/dev';
import babel from '@rolldown/plugin-babel';
import vscode from '@tomjs/vite-plugin-vscode';
import react, { reactCompilerPreset } from '@vitejs/plugin-react';
import type { Alias, Plugin, UserConfig } from 'vite';

/** Default CSP: the plugin's default lacks font-src/img-src and blocks
 *  dynamically imported chunks (script-src nonce-only) — the app bundle
 *  code-splits lazy providers, and Inter ships as woff2 assets. Allow the
 *  webview resource origin explicitly. */
export const DEFAULT_WEBVIEW_CSP = `<meta http-equiv="Content-Security-Policy" content="default-src 'none'; img-src {{cspSource}} https: data:; script-src {{cspSource}} 'nonce-{{nonce}}' 'unsafe-eval'; style-src {{cspSource}} 'unsafe-inline'; font-src {{cspSource}} data:; connect-src {{cspSource}} https:;">`;

export interface VscodeTargetOptions {
  /** Absolute path of the vscode target dir (vite root: index.html +
   *  extension/ + webview/). */
  targetDir: string;
  /** Absolute output dir (staging root: extension/ + webview/ +
   *  generated package.json). Keep it under the app's dist/. */
  outDir: string;
  /** Absolute path to the Tamagui config compiled into the webview. */
  tamaguiConfig: string;
  /** Workspace root (defaults to the git toplevel). */
  workspaceRoot?: string;
  /** Webview CSP meta (defaults to DEFAULT_WEBVIEW_CSP). */
  csp?: string;
  isDev?: boolean;
  /** Extra defines merged over the factory defaults. */
  define?: Record<string, unknown>;
  /** Extra resolve aliases appended after the factory's. */
  aliases?: Alias[];
}

const WEB_EXTENSIONS = [
  '.web.tsx',
  '.web.ts',
  '.web.jsx',
  '.web.js',
  '.mjs',
  '.mts',
  '.tsx',
  '.ts',
  '.jsx',
  '.js',
  '.json',
];

/** Resolve the seam's one-adapter: workspace source when developing inside
 *  the framework monorepo, the built package export otherwise. */
export function resolveSeamOneAdapter(workspaceRoot: string): string {
  const source = path.join(workspaceRoot, 'public/router/src/seam/oneAdapter.tsx');
  if (fs.existsSync(source)) {
    return source;
  }
  return '@repo/router/seam';
}

export async function createVscodeConfig(options: VscodeTargetOptions): Promise<UserConfig> {
  const workspaceRoot = options.workspaceRoot ?? lookupProjectRoot();
  const isDev = options.isDev ?? process.env.NODE_ENV !== 'production';
  const { tamaguiPlugin } = await import('@tamagui/vite-plugin');
  // The webview entry imports tamagui.css, but the tamagui plugin only
  // writes outputCSS DURING the build — seed it so a fresh clone's first
  // build doesn't die on an unresolvable import.
  const outputCSS = path.join(options.targetDir, 'tamagui.css');
  if (!fs.existsSync(outputCSS)) {
    fs.writeFileSync(outputCSS, '/* generated by @tamagui/vite-plugin during build */\n');
  }
  return {
    root: options.targetDir,
    // Always root-absolute: the vscode plugin rewrites built asset URLs as
    // `{{baseUri}}${attr}` (string concatenation), so a "./"-relative base
    // would produce `<baseUri>./assets/…` — a literal `webview./assets`
    // path segment the webview resource host 404s.
    base: '/',
    build: {
      outDir: options.outDir,
      emptyOutDir: true,
      minify: false,
      sourcemap: true,
    },
    define: {
      __DEV__: JSON.stringify(isDev),
      // React-native deps assume Node/RN's `global` at render time.
      global: 'globalThis',
      'process.env.NODE_ENV': JSON.stringify(isDev ? 'development' : 'production'),
      'process.env.TAMAGUI_TARGET': JSON.stringify('web'),
      ...options.define,
    },
    plugins: [
      stubExpoTypeDeclarations(),
      oneServerOnlyBrowserStub(workspaceRoot),
      react({ jsxRuntime: 'automatic' }),
      // Same React Compiler pass the One app runs — the webview gets the
      // memoization for free (react 19 built-in runtime).
      babel({ presets: [reactCompilerPreset()] }),
      tamaguiPlugin({
        components: lookupTamaguiModules([options.targetDir]),
        config: options.tamaguiConfig,
        outputCSS: path.join(options.targetDir, 'tamagui.css'),
      }) as Plugin,
      vscode({
        recommended: true,
        extension: {
          // tsdown resolves relative entries from process.cwd() (the app
          // root), not the vite root — hand it the absolute path.
          entry: path.join(options.targetDir, 'extension/index.ts'),
        },
        webview: {
          csp: options.csp ?? DEFAULT_WEBVIEW_CSP,
        },
      }),
    ],
    resolve: {
      alias: [
        ...Object.entries(workspaceSourceAliases(workspaceRoot)).map(([find, replacement]) => ({
          find,
          replacement,
        })),
        // One routing layer: `one` rides the stack-navigation seam.
        { find: /^one$/, replacement: resolveSeamOneAdapter(workspaceRoot) },
        { find: '@', replacement: path.join(options.targetDir, 'webview') },
        { find: 'react-native', replacement: 'react-native-web' },
        // Force every "react", "react-dom", and jsx-runtime import to the
        // workspace copy. Without this, transitive imports from `one` resolve
        // to its vendored React 18 (one/vendor/react/...), which uses internal
        // APIs (ReactCurrentOwner) that React 19 has removed — crashing the
        // webview at first render.
        { find: /^react$/, replacement: path.join(workspaceRoot, 'node_modules/react') },
        { find: /^react-dom$/, replacement: path.join(workspaceRoot, 'node_modules/react-dom') },
        {
          find: 'react/jsx-runtime',
          replacement: path.join(workspaceRoot, 'node_modules/react/jsx-runtime.js'),
        },
        {
          find: 'react/jsx-dev-runtime',
          replacement: path.join(workspaceRoot, 'node_modules/react/jsx-dev-runtime.js'),
        },
        ...(options.aliases ?? []),
      ],
      dedupe: ['react', 'react-dom'],
      extensions: WEB_EXTENSIONS,
      mainFields: ['browser', 'module', 'main'],
    },
    optimizeDeps: {
      include: [
        'react',
        'react-dom',
        '@tamagui/core',
        '@tamagui/web',
        'tamagui',
        'react-native-web',
        '@repo/ui',
      ],
      esbuildOptions: {
        resolveExtensions: ['.web.ts', '.web.tsx', '.web.js', '.web.jsx', '.ts', '.tsx', '.js', '.jsx'],
        mainFields: ['module', 'main'],
      },
    },
    server: {
      host: '0.0.0.0',
      port: 5173,
      strictPort: true,
      hmr: {
        host: 'localhost',
        port: 5173,
        protocol: 'ws',
      },
    },
  };
}

// ── vsce staging manifest ─────────────────────────────────────────

export interface VsceManifest {
  name: string;
  displayName?: string;
  publisher: string;
  version: string;
  description?: string;
  /** "module" when the extension host is built ESM (VS Code ≥1.100). */
  type?: 'module' | 'commonjs';
  /** Defaults to `{ vscode: "^1.75.0" }`. */
  engines?: { vscode: string; [key: string]: string };
  /** Defaults to `extension/index.js` (the staging layout). */
  main?: string;
  contributes?: Record<string, unknown>;
  activationEvents?: string[];
  categories?: string[];
  icon?: string;
  repository?: unknown;
  license?: string;
}

/** Correct the webview dist path baked into the extension-host bundle.
 *
 *  @tomjs/vite-plugin-vscode computes `VITE_WEBVIEW_DIST` (the segment its
 *  runtime joins onto `context.extensionUri` to form the webview base URI)
 *  by stripping `process.cwd()` off the resolved outDir. That model assumes
 *  the extension is packaged from the vite project root; with an
 *  out-of-tree staging dir (ours: apps/<name>/dist-vscode + generated
 *  manifest) the strip misses and the BUILD MACHINE'S ABSOLUTE PATH gets
 *  baked into the bundle — at runtime the webview base URI doubles into
 *  `…/dist-vscode/Users/…/dist-vscode/webview` and every asset 404s.
 *
 *  In the staging layout the correct value is always the literal
 *  `"webview"` (the assets dir next to the generated package.json), so the
 *  staging step rewrites the joinPath call site — anchored on the
 *  `.extensionUri` property read, which survives minification. */
export async function fixStagedWebviewAssetUris(stagingDir: string): Promise<boolean> {
  const bundles = ['extension/index.js', 'extension/index.cjs'].map((file) => path.join(stagingDir, file));
  let fixed = false;
  for (const bundle of bundles) {
    if (!fs.existsSync(bundle)) {
      continue;
    }
    const source = await fs.promises.readFile(bundle, 'utf-8');
    const rewritten = source.replaceAll(
      // The dist segment may be emitted as a quoted string OR a template
      // literal (tsdown's env define does both depending on content).
      /joinPath\(([A-Za-z_$][\w$]*\.extensionUri),\s*("[^"\n]*"|'[^'\n]*'|`[^`\n]*`)\)/g,
      'joinPath($1, "webview")',
    );
    if (rewritten !== source) {
      await fs.promises.writeFile(bundle, rewritten, 'utf-8');
      fixed = true;
    }
  }
  return fixed;
}

/** Write the extension-manifest package.json into the staging dir. A VS
 *  Code extension's package.json IS its manifest — the product app's own
 *  package.json (an Expo/One app manifest) can't double as it, so `vsce
 *  package` runs against the staging dir instead. Also applies
 *  `fixStagedWebviewAssetUris` — staging is the earliest race-free point after
 *  the plugin's detached extension-host build has finished. */
export async function writeVsceManifest(stagingDir: string, manifest: VsceManifest): Promise<void> {
  const { engines, main, ...rest } = manifest;
  const packageJson = {
    ...rest,
    main: main ?? 'extension/index.js',
    engines: { vscode: '^1.75.0', ...engines },
  };
  await fs.promises.mkdir(stagingDir, { recursive: true });
  await fs.promises.writeFile(
    path.join(stagingDir, 'package.json'),
    `${JSON.stringify(packageJson, null, 2)}\n`,
    'utf-8',
  );
  await fixStagedWebviewAssetUris(stagingDir);
}
