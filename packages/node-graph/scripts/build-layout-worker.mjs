#!/usr/bin/env node
// Bundles src/layout/worker.entry.ts (plus @dagrejs/dagre) into a classic IIFE
// and writes it into src/layout/worker.generated.ts as a string literal.
//
//   node scripts/build-layout-worker.mjs           rewrite the generated module
//   node scripts/build-layout-worker.mjs --check   exit 1 if it is stale
//   node scripts/build-layout-worker.mjs --sha     print the bundle's sha256
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

import { build, version } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const entry = path.join(root, 'src/layout/worker.entry.ts');
const target = path.join(root, 'src/layout/worker.generated.ts');

// es2019 lowers `?.`/`??`, which older WebView engines lack. Inline legal
// comments keep dagre's license notice inside the shipped string.
const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  minify: true,
  target: 'es2019',
  legalComments: 'inline',
  write: false,
  logLevel: 'silent',
});
const source = result.outputFiles[0].text;
const bytes = Buffer.byteLength(source, 'utf-8');
const sha256 = createHash('sha256').update(source).digest('hex');

if (process.argv.includes('--sha')) {
  process.stdout.write(`${sha256}\n`);
  process.exit(0);
}

const moduleText = `/**
 * GENERATED by scripts/build-layout-worker.mjs. Do not edit.
 *
 * The layout worker — \`src/layout/worker.entry.ts\` plus @dagrejs/dagre —
 * bundled to a CLASSIC IIFE and committed as a string, design §8.
 *
 * Run \`node scripts/build-layout-worker.mjs\` to rebuild and
 * \`node scripts/build-layout-worker.mjs --check\` to prove it is current. The
 * package's own \`build\` script runs the check as its prefix and
 * \`worker.generated.test.ts\` re-runs the bundler in process, so a stale
 * string cannot ship.
 *
 * Measured at generation time:
 *
 *   ${bytes.toLocaleString('en-US')} bytes, esbuild ${version}
 *   sha256 ${sha256}
 *
 * It is instantiated as \`new Worker(URL.createObjectURL(new Blob([source])))\`
 * — no module type, no origin, no bundler cooperation — because the WebView an
 * Expo DOM component runs has none of those things. \`import.meta\` and
 * \`elkjs\` are both asserted absent from this string by the spec.
 */

// A 50 KB literal. The formatter would rewrap the assignment and switch the
// quote style, and \`--check\` compares this file byte for byte.
// oxfmt-ignore
export const layoutWorkerSource: string = ${JSON.stringify(source)};

// oxfmt-ignore
export const layoutWorkerSha256 = "${sha256}";

export const layoutWorkerBytes = ${bytes};
`;

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf-8') !== moduleText) {
    process.stderr.write(
      'src/layout/worker.generated.ts is stale. Run `node scripts/build-layout-worker.mjs` and commit the result.\n',
    );
    process.exit(1);
  }
  process.exit(0);
}

writeFileSync(target, moduleText);
process.stdout.write(`wrote ${bytes} bytes, sha256 ${sha256}\n`);
